function targetScore(target: string): number {
  if (target === "D25") return 50;
  if (target === "25" || target === "S25") return 25;
  if (target.startsWith("T")) return Number(target.slice(1)) * 3;
  if (target.startsWith("D")) return Number(target.slice(1)) * 2;
  if (target.startsWith("S")) return Number(target.slice(1));
  return Number(target) || 0;
}

export function computeCheckoutSuggestionsLocal(
  remaining: number,
  dartsThrown: number,
  outMode: string,
): (string | null)[] {
  const suggestions: (string | null)[] = [null, null, null];
  const startIdx = Math.max(0, Math.min(2, dartsThrown));

  if (remaining <= 0 || remaining > 170) {
    return suggestions;
  }

  if (outMode === "double") {
    const finish = DOUBLE_FINISHES[remaining];
    if (finish && finish.length > 0) {
      for (let i = startIdx; i < 3; i += 1) {
        suggestions[i] = finish[i - startIdx] ?? null;
      }
      return suggestions;
    }
  }

  let currentRemaining = remaining;
  for (let i = startIdx; i < 3; i += 1) {
    if (currentRemaining <= 0) {
      suggestions[i] = null;
      continue;
    }

    let target: string | undefined;
    if (outMode === "double") {
      target = currentRemaining > 170 ? "T20" : "T19";
    } else {
      target = NEXT_TARGET_SINGLE_OUT[currentRemaining];
      if (!target) {
        target = currentRemaining > 60 ? "T20" : "T19";
      }
    }

    suggestions[i] = target;
    currentRemaining -= targetScore(target);
  }
  return suggestions;
}

